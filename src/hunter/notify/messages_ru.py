def sanitize(text: str | None) -> str:
    """Экранирует спецсимволы HTML для безопасного вывода пользовательских строк."""
    if not text:
        return ""
    return html.escape(str(text), quote=True)


def clean_name(name: str | None, max_len: int = 40) -> str:
    """Очищает имя пользователя:

    - Удаляет управляющие символы (ASCII 0-31, 127-159)
    - Обрезает до max_len символов (по умолчанию 40)
    - Экранирует HTML спецсимволы
    - Возвращает 'Пользователь', если имя пустое
    """
    if not name:
        return "Пользователь"
    # Удаляем управляющие символы
    cleaned = re.sub(r"[\x00-\x1f\x7f-\x9f]", "", str(name))
    cleaned = cleaned.strip()
    if not cleaned:
        return "Пользователь"
    if len(cleaned) > max_len:
        cleaned = cleaned[:max_len].rstrip()
    return html.escape(cleaned, quote=True)
